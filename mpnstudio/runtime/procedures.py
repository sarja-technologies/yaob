def _eval_prop(expr: str, env: dict[str, bool]) -> bool:
    """Evaluate a propositional formula with a small recursive-descent parser (no eval)."""
    import re
    tokens = re.findall(r"<->|->|[()~&|]|[A-Za-z]\w*", expr)
    need("".join(tokens) == expr.replace(" ", ""), "use variables with ~ (not), & (and), | (or), -> (implies), <-> (iff) and parentheses")
    pos = 0

    def peek():
        return tokens[pos] if pos < len(tokens) else None

    def take(t=None):
        nonlocal pos
        need(pos < len(tokens) and (t is None or tokens[pos] == t), "malformed formula")
        pos += 1
        return tokens[pos - 1]

    def atom():
        t = take()
        if t == "(":
            v = iff()
            take(")")
            return v
        if t == "~":
            return not atom()
        need(t in env, f"unexpected token {t!r}")
        return env[t]

    def conj():
        v = atom()
        while peek() == "&":
            take()
            rhs = atom()
            v = v and rhs
        return v

    def disj():
        v = conj()
        while peek() == "|":
            take()
            rhs = conj()
            v = v or rhs
        return v

    def impl():
        v = disj()
        if peek() == "->":
            take()
            rhs = impl()                 # always parse the right side, even when the left side decides the value
            return (not v) or rhs
        return v

    def iff():
        v = impl()
        while peek() == "<->":
            take()
            v = v == impl()
        return v

    out = iff()
    need(pos == len(tokens), "malformed formula")
    return out


def _prop_vars(expr: str) -> list[str]:
    import re
    return sorted(set(re.findall(r"[A-Za-z]\w*", expr)))


@proc("logic.truth_table", "Truth table", PL, "Classify a propositional formula as a tautology, contradiction or contingency by its truth table.", {"formula": S},
      "evaluate the formula under every assignment of its variables", constraints=["operators ~ & | -> <->", "at most 8 variables"], concept="Truth table", shared=[M, CS],
      ex=({"formula": "(p -> q) <-> (~q -> ~p)"}, {"variables": ["p", "q"], "true_rows": 4, "rows": 4, "classification": "tautology"}))
def _tt(formula):
    vs = _prop_vars(formula)
    need(1 <= len(vs) <= 8, "use between one and eight variables")
    true = 0
    for i in range(2 ** len(vs)):
        env = {v: bool((i >> k) & 1) for k, v in enumerate(vs)}
        true += _eval_prop(formula, env)
    rows = 2 ** len(vs)
    return {"variables": vs, "true_rows": true, "rows": rows,
            "classification": "tautology" if true == rows else "contradiction" if true == 0 else "contingency"}


@proc("logic.equivalent", "Logical equivalence", PL, "Whether two propositional formulas have the same truth value under every assignment.", {"a": S, "b": S},
      "compare truth tables over the union of variables", constraints=["operators ~ & | -> <->", "at most 8 variables"], concept="Logical equivalence", shared=[M, CS],
      ex=({"a": "~(p & q)", "b": "~p | ~q"}, True))
def _equiv(a, b):
    vs = sorted(set(_prop_vars(a)) | set(_prop_vars(b)))
    need(1 <= len(vs) <= 8, "use between one and eight variables")
    for i in range(2 ** len(vs)):
        env = {v: bool((i >> k) & 1) for k, v in enumerate(vs)}
        if _eval_prop(a, env) != _eval_prop(b, env):
            return False
    return True


@proc("logic.valid_argument", "Validity of an argument", PL, "Whether a conclusion follows from premises in propositional logic.", {"premises": S, "conclusion": S},
      "valid when no assignment makes every premise true and the conclusion false", constraints=["premises separated by ';'", "at most 8 variables"],
      concept="Validity (logic)", shared=[M], ex=({"premises": "p -> q; p", "conclusion": "q"}, True))
def _valid(premises, conclusion):
    ps = [p.strip() for p in premises.split(";") if p.strip()]
    need(ps, "give at least one premise")
    vs = sorted(set(v for p in ps for v in _prop_vars(p)) | set(_prop_vars(conclusion)))
    need(1 <= len(vs) <= 8, "use between one and eight variables")
    for i in range(2 ** len(vs)):
        env = {v: bool((i >> k) & 1) for k, v in enumerate(vs)}
        if all(_eval_prop(p, env) for p in ps) and not _eval_prop(conclusion, env):
            return False
    return True


