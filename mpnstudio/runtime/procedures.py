@proc("math.pearson", "Pearson correlation coefficient", M, "Linear correlation between two equally long lists.", {"x": L, "y": L},
      "r = cov(x, y) / (sd_x * sd_y)", constraints=["same length", "at least two points", "neither list constant"],
      concept="Pearson correlation coefficient", shared=[PS], ex=({"x": [1, 2, 3], "y": [2, 4, 6]}, 1.0))
def _pearson(x, y):
    need(len(x) == len(y) and len(x) >= 2, "the lists must have the same length of at least two")
    mx, my = sum(x) / len(x), sum(y) / len(y)
    sx = math.sqrt(sum((a - mx) ** 2 for a in x))
    sy = math.sqrt(sum((b - my) ** 2 for b in y))
    need(sx > 0 and sy > 0, "a constant list has no correlation")
    return sum((a - mx) * (b - my) for a, b in zip(x, y)) / (sx * sy)


@proc("math.linear_regression", "Simple linear regression", M, "Least-squares line through points.", {"x": L, "y": L},
      "slope = cov(x, y) / var(x); intercept = mean_y - slope * mean_x", constraints=["same length", "x not constant"],
      concept="Linear regression", ex=({"x": [0, 1, 2], "y": [1, 3, 5]}, {"slope": 2.0, "intercept": 1.0}))
def _linreg(x, y):
    need(len(x) == len(y) and len(x) >= 2, "the lists must have the same length of at least two")
    mx, my = sum(x) / len(x), sum(y) / len(y)
    sxx = sum((a - mx) ** 2 for a in x)
    need(sxx > 0, "x must not be constant")
    slope = sum((a - mx) * (b - my) for a, b in zip(x, y)) / sxx
    return {"slope": round(slope, 10), "intercept": round(my - slope * mx, 10)}


