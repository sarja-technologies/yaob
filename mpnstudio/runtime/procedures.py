@proc("cs.caesar", "Caesar cipher", CS, "Shift each letter of a text by a fixed number of places.", {"text": S, "shift": I}, "letter -> letter + shift (mod 26)",
      concept="Caesar cipher", shared=[LA, HI], ex=({"text": "Hello", "shift": 3}, "Khoor"))
def _caesar(text, shift):
    out = []
    for ch in text:
        if "a" <= ch <= "z":
            out.append(chr((ord(ch) - 97 + shift) % 26 + 97))
        elif "A" <= ch <= "Z":
            out.append(chr((ord(ch) - 65 + shift) % 26 + 65))
        else:
            out.append(ch)
    return "".join(out)


@proc("cs.entropy", "Shannon entropy", CS, "Information entropy of a probability distribution, in bits.", {"probabilities": L}, "H = -sum(p_i log2 p_i)",
      constraints=["probabilities sum to 1", "each between 0 and 1"], concept="Entropy (information theory)", shared=[M], unit="bits", ex=({"probabilities": [0.5, 0.5]}, 1.0))
def _entropy(probabilities):
    need(probabilities and all(0 <= p <= 1 for p in probabilities) and abs(sum(probabilities) - 1) < 1e-6, "give probabilities between 0 and 1 that sum to 1")
    return -sum(p * math.log2(p) for p in probabilities if p > 0)


@proc("cs.f1_score", "Precision, recall and F1", CS, "Classification quality from counts of true positives, false positives and false negatives.",
      {"true_positive": I, "false_positive": I, "false_negative": I}, "precision = TP / (TP + FP); recall = TP / (TP + FN); F1 = 2PR / (P + R)",
      constraints=["non-negative counts", "TP > 0"], concept="Precision and recall", shared=[M], ex=({"true_positive": 8, "false_positive": 2, "false_negative": 8}, {"precision": 0.8, "recall": 0.5, "f1": 0.615385}))
def _f1(true_positive, false_positive, false_negative):
    need(true_positive > 0 and false_positive >= 0 and false_negative >= 0, "require TP > 0 and non-negative counts")
    p = true_positive / (true_positive + false_positive)
    r = true_positive / (true_positive + false_negative)
    return {"precision": round(p, 6), "recall": round(r, 6), "f1": round(2 * p * r / (p + r), 6)}


