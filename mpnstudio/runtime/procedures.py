def parse_formula(formula: str) -> dict[str, int]:
    """Parse a chemical formula with nested parentheses, e.g. Ca(OH)2 or Al2(SO4)3."""
    import re
    tokens = re.findall(r"[A-Z][a-z]?|\d+|\(|\)", formula)
    need("".join(tokens) == formula.replace(" ", "") and tokens, f"cannot parse the formula {formula!r}")
    stack: list[dict[str, int]] = [{}]
    i = 0
    while i < len(tokens):
        t = tokens[i]
        if t == "(":
            stack.append({})
        elif t == ")":
            need(len(stack) > 1, "unbalanced parentheses")
            grp = stack.pop()
            mult = 1
            if i + 1 < len(tokens) and tokens[i + 1].isdigit():
                mult = int(tokens[i + 1])
                i += 1
            for k, v in grp.items():
                stack[-1][k] = stack[-1].get(k, 0) + v * mult
        elif t.isdigit():
            raise ProcedureError("unexpected number in the formula")
        else:
            need(t in ATOMIC_MASS, f"unknown or unsupported element {t!r}")
            n = 1
            if i + 1 < len(tokens) and tokens[i + 1].isdigit():
                n = int(tokens[i + 1])
                i += 1
            stack[-1][t] = stack[-1].get(t, 0) + n
        i += 1
    need(len(stack) == 1, "unbalanced parentheses")
    return stack[0]


