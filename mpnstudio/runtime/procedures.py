@proc("cs.luhn", "Luhn checksum", CS, "Whether a digit string passes the Luhn check used by payment card numbers.", {"digits": S}, "double every second digit from the right; sum of digits mod 10 = 0",
      constraints=["digits only"], concept="Luhn algorithm", ex=({"digits": "79927398713"}, True))
def _luhn(digits):
    d = digits.replace(" ", "")
    need(d.isdigit() and d, "give a string of digits")
    total = 0
    for i, ch in enumerate(reversed(d)):
        n = int(ch)
        if i % 2:
            n = n * 2 - 9 if n > 4 else n * 2
        total += n
    return total % 10 == 0


