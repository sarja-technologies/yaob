@proc("math.prime_factors", "Prime factorisation", M, "Prime factors of an integer, with repetition.", {"n": I}, "trial division",
      constraints=["2 <= n <= 10^12"], concept="Integer factorization", ex=({"n": 360}, [2, 2, 2, 3, 3, 5]))
def _factors(n):
    need(2 <= n <= 10 ** 12, "n must be between 2 and 10^12")
    out, d = [], 2
    while d * d <= n:
        while n % d == 0:
            out.append(d)
            n //= d
        d += 1 if d == 2 else 2
    if n > 1:
        out.append(n)
    return out


@proc("math.is_prime", "Primality test", M, "Whether an integer is prime.", {"n": I}, "no divisor between 2 and sqrt(n)",
      constraints=["n <= 10^12"], concept="Prime number", ex=({"n": 7919}, True))
def _is_prime(n):
    need(n <= 10 ** 12, "n must be at most 10^12")
    if n < 2:
        return False
    if n % 2 == 0:
        return n == 2
    d = 3
    while d * d <= n:
        if n % d == 0:
            return False
        d += 2
    return True


