@proc("math.bayes", "Bayes' theorem", M, "Probability of a hypothesis after evidence.", {"prior": N, "likelihood": N, "false_positive_rate": N},
      "P(H|E) = P(E|H) P(H) / (P(E|H) P(H) + P(E|not H) (1 - P(H)))", constraints=["all inputs between 0 and 1"],
      concept="Bayes' theorem", shared=[PL, MD], ex=({"prior": 0.01, "likelihood": 0.9, "false_positive_rate": 0.05}, 0.1538461538))
def _bayes(prior, likelihood, false_positive_rate):
    need(all(0 <= v <= 1 for v in (prior, likelihood, false_positive_rate)), "probabilities must lie between 0 and 1")
    den = likelihood * prior + false_positive_rate * (1 - prior)
    need(den > 0, "the evidence has zero probability")
    return likelihood * prior / den


