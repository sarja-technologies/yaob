@proc("cs.base_convert", "Number base conversion", CS, "Convert an integer between bases 2 to 36.", {"number": S, "from_base": I, "to_base": I},
      "parse digits in the source base; emit digits in the target base", constraints=["2 <= base <= 36", "digits valid in the source base"],
      concept="Radix", shared=[M], ex=({"number": "255", "from_base": 10, "to_base": 2}, "11111111"), aliases=["binary", "hexadecimal"])
def _base(number, from_base, to_base):
    need(2 <= from_base <= 36 and 2 <= to_base <= 36, "bases must be between 2 and 36")
    try:
        n = int(number.strip().lower().replace("_", ""), from_base)
    except ValueError:
        raise ProcedureError(f"{number!r} is not a valid base-{from_base} integer")
    if n == 0:
        return "0"
    digits, neg, out = "0123456789abcdefghijklmnopqrstuvwxyz", n < 0, []
    n = abs(n)
    while n:
        n, r = divmod(n, to_base)
        out.append(digits[r])
    return ("-" if neg else "") + "".join(reversed(out))


