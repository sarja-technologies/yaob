@proc("cs.levenshtein", "Levenshtein distance", CS, "Minimum single-character edits turning one string into another.", {"a": S, "b": S}, "dynamic programming over insert, delete, substitute",
      constraints=["each string at most 2000 characters"], concept="Levenshtein distance", shared=[LA], ex=({"a": "kitten", "b": "sitting"}, 3))
def _lev(a, b):
    need(len(a) <= 2000 and len(b) <= 2000, "strings are limited to 2000 characters")
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


