def self_test() -> list[str]:
    """Run every worked example. Returns failure descriptions (empty when all pass)."""
    bad = []
    for key, p in REGISTRY.items():
        if not p.examples:
            bad.append(f"{key}: no example")
        for args, want in p.examples:
            got = run(key, args)
            if not got["ok"]:
                bad.append(f"{key}: {got['error']}")
                continue
            r = got["result"]
            same = _close(r, want)
            if not same:
                bad.append(f"{key}: expected {want!r}, got {r!r}")
    return bad


def _close(a, b) -> bool:
    if isinstance(a, bool) or isinstance(b, bool) or isinstance(a, str) or isinstance(b, str):
        return a == b
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        return abs(a - b) <= 1e-6 * max(1.0, abs(b))
    if isinstance(a, dict) and isinstance(b, dict):
        return a.keys() == b.keys() and all(_close(a[k], b[k]) for k in a)
    if isinstance(a, (list, tuple)) and isinstance(b, (list, tuple)):
        return len(a) == len(b) and all(_close(x, y) for x, y in zip(a, b))
    return a == b


