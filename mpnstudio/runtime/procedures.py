@proc("math.mean", "Arithmetic mean", M, "Average of a list of numbers.", {"values": L}, "mean = (x1 + ... + xn) / n",
      constraints=["at least one value"], concept="Arithmetic mean", ex=({"values": [2, 4, 9]}, 5.0), aliases=["average"])
def _mean(values):
    need(len(values) > 0, "at least one value is required")
    return sum(values) / len(values)


@proc("math.median", "Median", M, "Middle value of a sorted list; mean of the two middle values when the count is even.", {"values": L},
      "sort; take the middle", constraints=["at least one value"], concept="Median", ex=({"values": [3, 9, 4, 12, 7]}, 7))
def _median(values):
    need(len(values) > 0, "at least one value is required")
    s = sorted(values)
    n = len(s)
    return s[n // 2] if n % 2 else (s[n // 2 - 1] + s[n // 2]) / 2


@proc("math.mode", "Mode", M, "Most frequent value or values in a list.", {"values": L}, "value(s) with the highest count",
      constraints=["at least one value"], concept="Mode (statistics)", ex=({"values": [1, 2, 2, 3, 3]}, [2, 3]))
def _mode(values):
    need(len(values) > 0, "at least one value is required")
    c: dict = {}
    for v in values:
        c[v] = c.get(v, 0) + 1
    top = max(c.values())
    return sorted(k for k, n in c.items() if n == top)


@proc("math.variance", "Variance", M, "Mean squared deviation from the mean; sample variance divides by n - 1.", {"values": L, "sample": "boolean?"},
      "var = sum((x - mean)^2) / n   (or n - 1 for a sample)", constraints=["two or more values for a sample"], concept="Variance",
      ex=({"values": [2, 4, 4, 4, 5, 5, 7, 9]}, 4.0))
def _variance(values, sample=False):
    n = len(values)
    need(n >= (2 if sample else 1), "not enough values")
    m = sum(values) / n
    return sum((x - m) ** 2 for x in values) / (n - 1 if sample else n)


