"""Deterministic procedures behind procedure nodes.

A procedure node's Thinking cell names an implementation key from this registry.
Only keys registered here can run: importing an MPN package never brings code
with it. Every procedure declares its parameters, the formula it applies, its
constraints, and at least one worked example, which the test-suite executes.

Results are computed, not generated by the language model. The runtime labels
them as tool results in the routing evidence.
"""
from __future__ import annotations

import datetime as _dt
import math
from dataclasses import dataclass, field
from fractions import Fraction
from typing import Any, Callable


@dataclass
class Procedure:
    key: str
    title: str
    family: str
    summary: str
    params: dict[str, str]
    formula: str
    fn: Callable[..., Any]
    constraints: list[str] = field(default_factory=list)
    shared: list[str] = field(default_factory=list)       # further MPN memberships
    concept: str = ""                                     # title of the knowledge node this procedure applies
    unit: str = ""
    examples: list[tuple[dict, Any]] = field(default_factory=list)
    aliases: list[str] = field(default_factory=list)


REGISTRY: dict[str, Procedure] = {}


class ProcedureError(ValueError):
    """A constraint of the procedure was violated by the arguments."""


def need(cond: bool, msg: str):
    if not cond:
        raise ProcedureError(msg)


def proc(key, title, family, summary, params, formula, *, constraints=(), shared=(), concept="", unit="", ex=(), aliases=()):
    def deco(fn):
        examples = list(ex) if ex and isinstance(ex[0], tuple) and isinstance(ex[0][0], dict) and len(ex) != 2 else ([tuple(ex)] if ex else [])
        if ex and len(ex) == 2 and isinstance(ex[0], dict):
            examples = [tuple(ex)]
        REGISTRY[key] = Procedure(key, title, family, summary, dict(params), formula, fn, list(constraints), list(shared),
                                  concept, unit, examples, list(aliases))
        return fn
    return deco


def coerce(spec: str, v: Any) -> Any:
    if spec == "number":
        if isinstance(v, bool) or not isinstance(v, (int, float, str)):
            raise ProcedureError("expected a number")
        return float(v) if not isinstance(v, int) else v
    if spec == "integer":
        if isinstance(v, bool):
            raise ProcedureError("expected an integer")
        f = float(v)
        need(f == int(f), "expected an integer")
        return int(f)
    if spec == "list[number]":
        need(isinstance(v, (list, tuple)), "expected a list of numbers")
        return [coerce("number", x) for x in v]
    if spec == "string":
        return str(v)
    if spec == "boolean":
        return bool(v)
    return v


def run(key: str, args: dict) -> dict:
    """Execute a procedure. Returns {ok, result, unit} or {ok: False, error}."""
    p = REGISTRY.get(key)
    if p is None:
        return {"ok": False, "error": f"unknown procedure {key!r}"}
    try:
        missing = [k for k in p.params if k not in args and not p.params[k].endswith("?")]
        need(not missing, f"missing arguments: {', '.join(missing)}")
        clean = {k: coerce(p.params[k].rstrip("?"), args[k]) for k in p.params if k in args}
        out = p.fn(**clean)
        if isinstance(out, float):
            need(math.isfinite(out), "result is not finite")
            out = round(out, 10)
        return {"ok": True, "result": out, "unit": p.unit, "procedure": key}
    except ProcedureError as e:
        return {"ok": False, "error": str(e), "procedure": key}
    except (ZeroDivisionError, OverflowError, ValueError, TypeError) as e:
        return {"ok": False, "error": f"{type(e).__name__}: {e}", "procedure": key}


