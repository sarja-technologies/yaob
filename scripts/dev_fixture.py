"""Build a small SYNTHETIC development store for working on the UI and API without the real corpus.

Everything in it is marked origin=synthetic. It is never used for training, evaluation or node counts.
Usage: python scripts/dev_fixture.py data/dev-fixture.sqlite [nodes]
"""
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from mpnstudio.corpus.families import FAMILIES
from mpnstudio.runtime.procedures import REGISTRY
from mpnstudio.store import layout, schemas
from mpnstudio.store.db import Store

path = Path(sys.argv[1])
n_nodes = int(sys.argv[2]) if len(sys.argv) > 2 else 1200
if path.exists():
    raise SystemExit(f"{path} exists")
rng = random.Random(7)
s = Store(path)
schemas.seed_schemas(s)
with s.edit(actor="dev-fixture", kind="import", message="SYNTHETIC development fixture") as tx:
    src = tx.put_source("synthetic", "synthetic", "Development fixture (synthetic)", "", "none", attribution="generated by scripts/dev_fixture.py")
    code = tx.put_source("authored", "reference", "MPN Studio procedure library", "mpnstudio/runtime/procedures.py", "project source")
    mp = {}
    doms = {}
    for slug, name, desc in FAMILIES:
        mp[slug] = tx.put_mpn(slug, name, "domain", desc)
        doms[slug] = []
        for j in range(rng.randint(2, 5)):
            d1 = tx.put_domain(mp[slug], f"area-{j}", f"Area {j + 1}")
            doms[slug].append(d1)
            for k in range(rng.randint(0, 3)):
                doms[slug].append(tx.put_domain(mp[slug], f"area-{j}--topic-{k}", f"Topic {j + 1}.{k + 1}", d1, 2))
    ids = []
    slugs = list(mp)
    for i in range(n_nodes):
        fam = rng.choice(slugs)
        nid = tx.put_node(title=f"Synthetic topic {i + 1}", summary=f"Synthetic placeholder record {i + 1} for interface development.",
                          origin="synthetic", validation="unverified",
                          cells={"knowledge": {"statements": [{"text": f"Synthetic statement {i + 1}a.", "source": str(src)},
                                                              {"text": f"Synthetic statement {i + 1}b.", "source": str(src)}],
                                               "facts": [{"property": "fixture index", "value": str(i + 1), "source": str(src)}]},
                                 "thinking": {"entity_class": ["synthetic record"], "cues": [f"topic{i + 1}"]},
                                 "reasoning": {"constraints": [{"kind": "validity", "text": "Synthetic: not knowledge."}], "checks": [], "referrals": []}})
        tx.set_membership(nid, mp[fam], rng.choice(doms[fam]))
        tx.link_source(nid, src, "fixture")
        if rng.random() < 0.1:
            tx.set_membership(nid, mp[rng.choice([x for x in slugs if x != fam])], None, "shared", {"basis": "fixture"})
        ids.append(nid)
    for key, p in list(REGISTRY.items())[:40]:
        nid = tx.put_node(uid=f"yaob:proc:{key}", type="procedure", title=p.title, summary=p.summary, origin="reference", validation="checked",
                          cells={"knowledge": {"statements": [{"text": p.summary, "source": str(code)}, {"text": "Formula: " + p.formula, "source": str(code)}]},
                                 "thinking": {"impl": key, "params": p.params, "formula": p.formula, "unit": p.unit},
                                 "reasoning": {"constraints": [{"kind": "precondition", "text": c} for c in p.constraints], "checks": [], "referrals": []}})
        tx.set_membership(nid, mp[p.family])
        tx.link_source(nid, code, key)
        ids.append(nid)
    for _ in range(n_nodes * 2):
        a, b = rng.sample(ids, 2)
        tx.put_edge(a, b, rng.choice(["related_to", "part_of", "mentions", "instance_of"]), origin="derived")
print(layout.compute_layout(s))
print(s.counts())
